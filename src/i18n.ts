export function isLocale(value: string | null | undefined): value is Locale {
  return Boolean(value && (locales as readonly string[]).includes(value));
}

export function message(locale: Locale, key: string): string {
  if (key in pageAliases) return message(locale, pageAliases[key]);
  if (key in chromeCopy[locale]) return chromeCopy[locale][key];
  if (key in homeCopy[locale]) return homeCopy[locale][key];
  if (key in listCopy[locale]) return listCopy[locale][key];
  if (key in contractEnglish) return contractCopy[locale][key] || contractEnglish[key];
  if (key in (dynamicCopy[locale] || {})) return dynamicCopy[locale][key];
  if (key in (pageCopy[locale] || {})) return pageCopy[locale][key];
  if (key in poolFilterCopy[locale]) return poolFilterCopy[locale][key];
  if (key in progressCopy[locale])
    return progressCopy[locale][key as keyof (typeof progressCopy)[Locale]];
  if (key === "independent") return footerCopy[locale];
  if (key === "medianGas") return gasEstimateLabel[locale];
  return (
    (locale === "en" ? en[key] : translations[locale][key]) || en[key] || key
  );
}

export function formatMessage(locale: Locale, key: string, values: Record<string, string | number>): string {
  return message(locale, key).replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

